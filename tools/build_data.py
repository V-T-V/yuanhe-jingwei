LABELS = ("州境：", "府境：", "八到：", "贡、赋：", "贡赋：", "管县")


def strip_tags(s):
    return re.sub(r"<[^>]+>", "", s).replace("\u3000", "").replace("\xa0", "").strip()


def parse_blocks():
    """顺序读全部章节 → 块流 [(kind, text, ch_idx)]（h 与 p 按文档序混排）"""
    blocks = []
    for f in sorted(glob.glob(os.path.join(RAW, "*.html"))):
        ch = int(os.path.basename(f)[:-5])
        html = open(f, encoding="utf-8", errors="replace").read()
        m = re.search(r"<article[^>]*>(.*?)</article>", html, re.S)
        if not m:
            continue
        art = m.group(1)
        for mm in re.finditer(r"<(h[1-6]|p)[^>]*>(.*?)</\1>", art, re.S):
            t = strip_tags(mm.group(2))
            if t and t not in BOILER and t != "下一篇":
                blocks.append((mm.group(1), t, ch))
    return blocks


PROSE_WORD = re.compile(r"[在去今故曰也为有置步里]")


def is_county_list(t, relax=False):
    if t.startswith("管县") and ("，" in t or "、" in t):
        return True
    t2 = t.rstrip("。")
    parts = [p.strip() for p in re.split(r"[，,、]", t2) if p.strip()]
    if len(parts) < (2 if relax else 3):
        return False
    return (all(1 <= len(p) <= 5 for p in parts)
            and not any(PROSE_WORD.search(p) for p in parts)
            and not re.search(r"[。：；]", t2))


def split_counties(t):
    body = re.sub(r"^管县[一二三四五六七八九十百]+", "", t).rstrip("。")
    out = []
    for p in re.split(r"[，,、]", body):
        p = p.strip()
        if p:
            out.append(p)
    return out


def main():
    blocks = parse_blocks()
    states = []          # 有文之州
    cur = None
    juan = None
    dao = None
    dao_seen = []

    def close():
        nonlocal cur
        if cur:
            states.append(cur)
        cur = None

    for kind, t, ch in blocks:
        jm = JUAN_RE.match(t)
        if jm:
            juan = cn2int(jm.group(1))
            continue
        if t in DAO_NAME:
            if cur:
                close()
            if t not in dao_seen:
                dao_seen.append(t)
            dao = t
            continue
        zm0 = ZHOU_RE.match(t)
        if zm0:
            t = zm0.group(1)
            close()
            dao_eff = DAO_OVERRIDE.get(t, dao)
            cur = {"n": t, "dao": dao_eff, "juan": juan, "ch": [ch],
                   "paras": [], "zhen": None, "counties": [], "county_paras": {},
                   "_list_ok": False}
            continue
        im = INLINE_STATE_RE.match(t)
        if im and t.count("，") <= 12:
            close()
            dao_eff = DAO_OVERRIDE.get(im.group(1), dao)
            cur = {"n": im.group(1), "dao": dao_eff, "juan": juan, "ch": [ch],
                   "paras": [], "zhen": None, "counties": [], "county_paras": {},
                   "_list_ok": False}
            # 余文按内容继续走（本段整体入 paras）
        if cur is None:
            continue
        cur["ch"].append(ch)
        zm = ZHEN_RE.search(t)
        if zm and not cur["zhen"] and len(t) < 60:
            cur["zhen"] = zm.group(1)
        if t in LABELS or t.endswith("：") or re.match(r"^[州府]境[。：]?$", t):
            cur["paras"].append(("label", t))
            cur["_list_ok"] = True     # 州境/八到/贡赋标签之后才可能出现县名录
            continue
        if re.match(r"^管县[一二三四五六七八九十百]+$", t):
            cur["paras"].append(("label", t))
            cur["_list_ok"] = True
            cur["_expect_list"] = True   # 「管县N」标题——下一块必为县名录
            continue
        if cur.get("_expect_list"):
            # 名录可能与首县条目同块：「岍源，岍阳…南由。岍源县」→ 句号切分
            head, _sep, tail = t.partition("。")
            if is_county_list(head, relax=True) and not cur["counties"]:
                cur["counties"] = split_counties(head)
                cur["paras"].append(("list", head))
                cur["_expect_list"] = False
                t = tail.strip()
                if not t:
                    continue
            else:
                cur["_expect_list"] = False
        if (cur.get("_list_ok") and not cur["counties"]) and is_county_list(t):
            cur["counties"] = split_counties(t)
            cur["paras"].append(("list", t))
            continue
        cur["_expect_list"] = False
        cm = COUNTY_HEAD_RE.match(t)
        if cm:
            cur["county_paras"].setdefault(cm.group(1) + "县", [])
            cur["_cur_county"] = cm.group(1) + "县"
            cur["paras"].append(("county", t))
            continue
        cur["paras"].append(("p", t))
        if cur.get("_cur_county"):
            cur["county_paras"][cur["_cur_county"]].append(t)
    close()

    # 附郭县 = 县名录首位（元和志体例）；州名规范
    for s in states:
        s["fg"] = s["counties"][0] + "县" if s["counties"] else None
        # 去重同名州（跨页续条不重建——ZHOU_RE 只在块独立出现，续页无州名块，安全）
    # 同州跨卷重号（如缺卷重编致两见）：合并同 (n, dao)
    merged = []
    for s in states:
        old = next((x for x in merged if x["n"] == s["n"] and x["dao"] == s["dao"]), None)
        if old:
            old["paras"].extend(s["paras"])
            old["counties"] = old["counties"] or s["counties"]
            old["county_paras"].update({k: v for k, v in s["county_paras"].items() if k not in old["county_paras"]})
            old["ch"] = sorted(set(old["ch"] + s["ch"]))
            if not old["zhen"]:
                old["zhen"] = s["zhen"]
        else:
            merged.append(s)
    states = merged

    # 坐标与今名（人工整编；src=derived）
    for s in states:
        co = COORDS.get(s["n"])
        s["c"] = [co[0], co[1]] if co else None
        s["now"] = co[2] if co else None
        s["conf"] = co[3] if co else None
        s["src"] = "derived" if co else None
        yan = next((t for k, t in s["paras"] if k == "p" and len(t) > 80), "")
        s["yan"] = yan[:180]
        # 八到/贡赋：传本多佚——标签存在而内容空者记 true
        labels = [t for k, t in s["paras"] if k == "label"]
        s["badao"] = "八到：" in labels
        s["gongfu"] = any(t.startswith("贡") for t in labels)
        s.pop("_cur_county", None)
        s.pop("_list_ok", None)
        s.pop("_expect_list", None)

    # 缺卷州份（有目无文——原书所载而四库本佚）
    lost_by_dao = {}
    for n, (dao, note) in LOST_STATES.items():
        lost_by_dao.setdefault(dao, []).append({"n": n, "note": note})

    # 节镇：文本标记优先，整编表补足
    for s in states:
        if not s["zhen"]:
            s["zhen"] = ZHEN_OF.get(s["n"])

    zhens = []
    seen_z = {}
    for s in states:
        z = s["zhen"]
        if z:
            seen_z.setdefault(z, []).append(s["n"])
    for z, members in seen_z.items():
        zhens.append({"n": z, "states": members, "dao": states and next(x["dao"] for x in states if x["n"] == members[0])})
    # 无文之镇（缺卷）
    for z, dao_name in LOST_ZHEN.items():
        if z not in seen_z:
            zhens.append({"n": z, "states": [], "dao": dao_name, "lost": True})
    # 排序：按首州卷号
    def zkey(z):
        mem = z["states"]
        if not mem:
            return (99, z["n"])
        st = next(x for x in states if x["n"] == mem[0])
        return (st["juan"] or 99, z["n"])
    zhens.sort(key=zkey)

    dao_objs = []
    for did, dname, color in DAOS:
        ss = [s for s in states if s["dao"] == dname]
        dao_objs.append({
            "id": did, "name": dname, "color": color,
            "states": [
                {"n": s["n"], "c": s["c"], "now": s["now"], "conf": s["conf"],
                 "src": s["src"], "xian": s["counties"], "fg": s["fg"],
                 "zhen": s["zhen"], "juan": s["juan"], "yan": s["yan"],
                 "badao": s["badao"], "gongfu": s["gongfu"], "ch": s["ch"][0]}
                for s in ss],
            "lost": lost_by_dao.get(dname, []),
            "present": dname in dao_seen or bool(ss),
        })

    out = {
        "meta": {
            "site": "元和经纬",
            "book": "元和郡县图志",
            "author": "唐·李吉甫",
            "year": "元和八年（813）成书",
            "source": "识典古籍 · 钦定四库全书本《元和郡县志》SK0967",
            "juan_total": 40, "juan_extant": None,
            "missing_juan": "宋本缺卷十九、二十、二十三、二十四、二十六、三十六（四库提要），卷十八缺半、卷二十五缺二页；淮南道整道佚",
            "zhen_total": 47,
        },
        "daos": dao_objs,
        "zhens": zhens,
    }
    js = "/* 元和经纬 · 结构化数据（build_data.py 生成，勿手改） */\nvar YH = "
    js += json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write(js)

    # stats
    n_states = len(states)
    n_coord = sum(1 for s in states if s["c"])
    n_counties = sum(len(s["counties"]) for s in states)
    n_county_entries = sum(len(s["county_paras"]) for s in states)
    stats = {
        "states": n_states, "states_coord": n_coord,
        "counties_listed": n_counties, "county_entries": n_county_entries,
        "daos_present": [d for d in dao_seen],
        "zhens_text": len([z for z in zhens if not z.get("lost")]),
        "zhens_lost": len([z for z in zhens if z.get("lost")]),
        "per_dao": {d["name"]: {"states": len(d["states"]), "xian": sum(len(s["xian"]) for s in d["states"]),
                                "lost": len(d["lost"])} for d in dao_objs},
    }
    with open(OUT_STATS, "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=1)
    print(f"州条目 {n_states}（坐标 {n_coord}）· 县名录 {n_counties} · 县条目 {n_county_entries}")
    print("道:", dao_seen)
    for d in dao_objs:
        print(f"  {d['name']}: {len(d['states'])}州 / 佚{len(d['lost'])}")


