def cn2int(s):
    n, cur = 0, 0
    for ch in s:
        if ch in CN_NUM and CN_NUM[ch] < 10:
            cur = CN_NUM[ch]
        elif ch == "十":
            n += (cur or 1) * 10
            cur = 0
        elif ch == "百":
            n += (cur or 1) * 100
            cur = 0
    return n + cur


